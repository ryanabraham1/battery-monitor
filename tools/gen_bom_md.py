"""Write docs/BOM.md: everything to buy, with purchase links.

    python tools/gen_bom_md.py        (run after gen_fab.py so fab/ir_node_BOM_full.csv is current)

Board parts come straight from the generated BOM. Off-board links are search links, because
individual marketplace listings change too often to pin.
"""
import csv
import os
import sys
from urllib.parse import quote_plus

sys.path.insert(0, os.path.dirname(__file__))
import design as D

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
REV_B = any(p["ref"] == "J14" for p in D.PARTS)


def amazon(q):
    return "[Amazon](https://www.amazon.com/s?k=%s)" % quote_plus(q)


def digikey(q):
    return "[Digi-Key](https://www.digikey.com/en/products/result?keywords=%s)" % quote_plus(q)


def ali(q):
    return "[AliExpress](https://www.aliexpress.com/wholesale?SearchText=%s)" % quote_plus(q)


def lcsc(code):
    return "[%s](https://www.lcsc.com/search?q=%s)" % (code, code)


rows = list(csv.reader(open(os.path.join(ROOT, "fab", "ir_node_BOM_full.csv"), encoding="utf8")))
parts = [r for r in rows[1:] if len(r) >= 12 and r[0] and not r[0].startswith("TOTAL")]
smt = [r for r in parts if r[9] == "JLC SMT"]
tht = [r for r in parts if r[9] != "JLC SMT"]
smt_cost = sum(float(r[11]) for r in smt)
tht_cost = sum(float(r[11]) for r in tht)
n_ext = sum(1 for r in smt if r[7] == "extended")

out = []
w = out.append
w("# Bill of materials and where to buy — rev %s" % ("B (120 A pulse)" if REV_B else "A (12 A pulse)"))
w("")
w("Generated by `tools/gen_bom_md.py`. Prices are single-quantity figures in USD and will drift; board")
w("part prices and stock were read from JLCPCB when the fab files were last generated. Links marked")
w("Amazon, AliExpress or Digi-Key are **search links**, not specific listings I have vetted: check the")
w("value and rating in the listing before buying.")
w("")
w("## 1. The board (order from JLCPCB)")
w("")
w("Upload `fab/ir_node_gerbers.zip`, then `fab/ir_node_BOM_JLC.csv` and `fab/ir_node_CPL_JLC.csv` for")
w("assembly. Order page: [jlcpcb.com](https://jlcpcb.com/). JLC supplies and places every part in this group.")
w("")
w("| What | Per board | Notes |")
w("|---|---|---|")
w("| Parts JLC places (%d part types) | $%.2f | %d of them are \"extended\" parts, about $3 each per order |" % (len(smt), smt_cost, n_ext))
if REV_B:
    w("| Bare board | about $3–4 at 10 pcs | 100 × 80 mm, 2 layers, **2 oz copper** (needed for the 120 A pulse and 60 A fuse) |")
else:
    w("| Bare board | about $1–4 at 10 pcs | 100 × 80 mm, 2 layers. 2 oz copper is the design default; 1 oz is cheaper and is enough for chargers up to about 10 A (see README) |")
w("")
w("## 2. Hand-solder parts for the board")
w("")
w("JLC's standard assembly does not place these through-hole parts. Add them to an")
w("[LCSC](https://www.lcsc.com/) cart (same company as JLC's parts library) or buy the equivalents anywhere.")
w("")
w("| Ref | Part | Qty per board | Each | Buy |")
w("|---|---|---|---|---|")
for r in tht:
    refs, qty, value, mpn, _, _, code = r[0], r[1], r[2], r[3], r[4], r[5], r[6]
    link = lcsc(code) if code else amazon("2.54mm male pin header strip")
    name = mpn if mpn else value
    extra = ""
    if refs.startswith("Q1"):
        extra = " or " + digikey("IRLB3034PBF") + " (buy genuine Infineon)"
    w("| %s | %s | %s | $%s | %s%s |" % (refs, name, qty, ("%.2f" % float(r[10])), link, extra))
w("| JP1 cap | 2.54 mm jumper cap, for the last node on the CAN chain only | 1 per system | $0.05 | %s |" % amazon("2.54mm jumper cap"))
w("")
w("Hand-solder parts total: **$%.2f per board**." % tht_cost)
w("")
w("## 3. Off-board parts, per node")
w("")
w("| Part | Qty | About | Buy | What to check in the listing |")
w("|---|---|---|---|---|")
if REV_B:
    w("| Load resistor, 0.2 Ω 100 W, aluminium-housed wirewound | 2 (in parallel) | $6–10 each | %s · %s · %s | 0.2 Ω (often written 0R2 or 0.2R), 100 W, gold aluminium case with two mounting holes |" % (
        amazon("0.2 ohm 100W aluminum shell wirewound resistor"), ali("0.2R 100W aluminum shell resistor"), digikey("HS100 0R2")))
    w("| Bolt-down MIDI fuse, 60 A, 32 V or higher | 1 + spare | $3–5 | %s · %s | \"MIDI\" or \"AMI\" style, 30 mm between hole centres, M5 holes, 60 A |" % (
        amazon("MIDI fuse 60A 32V bolt down"), digikey("MIDI fuse 60A 32V")))
else:
    w("| Load resistor, 1 Ω 100 W, aluminium-housed wirewound | 1 | $3–10 | %s · %s · %s | 1 Ω (1R), 100 W, gold aluminium case with two mounting holes |" % (
        amazon("1 ohm 100W aluminum shell wirewound resistor"), ali("1R 100W aluminum shell resistor"), digikey("HS100 1R")))
w("| Metal plate or heatsink for the resistor%s | 1 | scrap | – | Any aluminium offcut; the resistor must not be mounted on plastic or wood |" % ("s" if REV_B else ""))
w("")
w("### Things you said you already have")
w("")
w("Listed so nothing is forgotten; search links in case you run short.")
w("")
w("| Part | Qty per node | Buy |")
w("|---|---|---|")
if REV_B:
    w("| Anderson SB50 housing with 6 AWG contacts (battery side) | 1 | %s |" % amazon("Anderson SB50 connector 6 AWG"))
    w("| Anderson SB50 housing with 10–12 AWG contacts (charger side) | 1 | %s |" % amazon("Anderson SB50 connector 10-12 AWG"))
    w("| 6 AWG wire, red and black (battery pigtail) | ~0.3 m each | %s |" % amazon("6 AWG silicone wire red black"))
    w("| 8 AWG wire (load bank) | ~0.6 m | %s |" % amazon("8 AWG silicone wire"))
    w("| 10–12 AWG wire (charger pigtail) | ~0.3 m each | %s |" % amazon("10 AWG silicone wire red black"))
    w("| Ring terminals: 6 AWG M5 ×1, 6 AWG M4 ×1, 8 AWG M4 ×2 plus resistor ends, 10–12 AWG M4 ×2 | 1 set | %s |" % amazon("ring terminal assortment 6 AWG 8 AWG M4 M5"))
    w("| M5 × 20 bolts, 2 plain nuts + 1 lock nut each, washers (fuse studs) | 2 sets | %s |" % amazon("M5x20 bolt nut washer assortment"))
    w("| M4 × 10 screws, nuts, lock washers (lug pads) | 5 sets | %s |" % amazon("M4x10 screw nut washer assortment"))
else:
    w("| Anderson SB50 housing with 10–12 AWG contacts | 2 | %s |" % amazon("Anderson SB50 connector 10-12 AWG"))
    w("| 10 AWG wire, red and black | ~0.5 m each | %s |" % amazon("10 AWG silicone wire red black"))
    w("| 14 AWG wire (load resistor) | ~0.5 m | %s |" % amazon("14 AWG silicone wire"))
    w("| Ring terminals, M4 stud: 10–12 AWG ×4, 14–16 AWG ×2 | 6 | %s |" % amazon("ring terminal M4 10-12 AWG"))
    w("| M4 × 10 screws, nuts, lock washers (lug pads) | 6 sets | %s |" % amazon("M4x10 screw nut washer assortment"))
w("| M3 × 16 screws (case) | 4 | %s |" % amazon("M3x16 screw"))
w("| Ethernet patch cable to the next node | 1 | %s |" % amazon("cat5e patch cable 3ft"))
w("| Filament for the case (PETG or ASA), about 70 g | – | %s |" % amazon("PETG filament 1.75mm"))
w("")
w("## 4. Hub (one for the whole pit)")
w("")
w("| Part | Qty | About | Buy | Notes |")
w("|---|---|---|---|---|")
w("| Raspberry Pi Zero 2 W **with header** (cheapest), or a Pi 3B+/4/5 you already own | 1 | $15–20 (Zero 2 W) or $45–60 (Pi 4) | [Zero 2 W](https://www.raspberrypi.com/products/raspberry-pi-zero-2-w/) · [Pi 4](https://www.raspberrypi.com/products/raspberry-pi-4-model-b/) | The product pages list approved resellers. The Zero needs the 40-pin header fitted (\"WH\" version, or solder one on); `case/pi_tray.stl` is sized for the full-size boards |")
w("| Waveshare RS485 CAN HAT (MCP2515) | 1 | $14–18 | [Waveshare](https://www.waveshare.com/rs485-can-hat.htm) · %s | Read the crystal marking (8.000 or 12.000) for the install script |" % amazon("Waveshare RS485 CAN HAT"))
w("| microSD card, 16 GB or larger | 1 | $6–8 | %s | |" % amazon("microSD card 32GB"))
w("| Power supply for the Pi | 1 | $8–10 | [Raspberry Pi power supplies](https://www.raspberrypi.com/products/#power-supplies-and-cables) | Micro-USB 5 V 2.5 A for a Zero 2 W or 3B+; USB-C 5 V 3 A for a Pi 4 |")
w("| Ethernet patch cable to cut in half | 1 | have | – | Bare end goes into the HAT's CAN terminals |")
w("| M2.5 × 6 screws | 4 | have | %s | Pi to the printed tray |" % amazon("M2.5x6 screw"))
w("")
w("## 5. What it adds up to")
w("")
per_node_lo = smt_cost + tht_cost + (12 + 3 if REV_B else 3)
per_node_hi = smt_cost + tht_cost + (20 + 5 if REV_B else 10)
w("Per node, parts only (board parts + hand-solder parts + off-board parts above, not counting what you")
w("already have): **about $%.0f–%.0f**. On top of that the JLCPCB order carries fixed costs that are shared" % (per_node_lo, per_node_hi))
w("across the batch: bare boards, assembly setup, the extended-part fees and shipping, roughly $%s for" % ("120–170" if REV_B else "100–160"))
w("ten boards. The hub is about $45–60 with a Pi Zero 2 W.")
w("")

open(os.path.join(ROOT, "docs", "BOM.md"), "w", encoding="utf8", newline="\n").write("\n".join(out))
print("wrote docs/BOM.md  (rev %s, SMT $%.2f, hand-solder $%.2f, %d extended)" % ("B" if REV_B else "A", smt_cost, tht_cost, n_ext))
